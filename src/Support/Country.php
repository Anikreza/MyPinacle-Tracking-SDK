 * Country to ISO 3166-1 alpha-2, lowercase (Meta `country`), from whatever an address or setting holds: "BD", "bgd",
 * "Bangladesh", "বাংলাদেশ", "United Kingdom". Unknown values give null so the field is omitted rather than guessed.
