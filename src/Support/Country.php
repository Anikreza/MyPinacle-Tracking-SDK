    /** First candidate that normalises to a known country (order = priority: shipping address, customer, store default). */
    public static function resolve(mixed ...$candidates): ?string
    {
        foreach ($candidates as $c) {
            if (($code = self::normalize(is_scalar($c) ? (string) $c : null)) !== null) {
                return $code;
            }
        }

        return null;
    }

    public static function normalize(?string $value): ?string
    {
        $v = (string) preg_replace('/\s+/u', ' ', mb_strtolower(trim((string) $value)));
        if ($v === '') {
            return null;
        }
        if (strlen($v) === 2) {
            return isset(self::ISO2[$v]) ? $v : (self::NAMES[$v] ?? null);
        }
        if (strlen($v) === 3 && isset(self::ISO3[$v])) {
            return self::ISO3[$v];
        }

        return self::NAMES[$v] ?? self::NAMES[(string) preg_replace('/^the /', '', $v)] ?? null;
    }

